-- Úsalo como entregable de DDL, o pégalo en Supabase > SQL Editor
-- SOLO si NO vas a usar `python manage.py migrate` (no hagas ambos).
--
-- Cambios respecto a la versión anterior:
--   * servicios_cliente: se elimina el RUT (minimización de datos).
--     El teléfono pasa a ser el identificador de la clienta.
--   * Email opcional (NULL, no cadena vacía) con unicidad parcial.
--   * Consentimiento de la política de privacidad (booleano + fecha).
--   * Row Level Security activado en todas las tablas.
-- =====================================================================
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE servicios_servicio (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoria        VARCHAR(20)   NOT NULL DEFAULT 'otros' CHECK (categoria IN ('manos','pies','otros')),
  nombre           VARCHAR(100)  NOT NULL,
  descripcion      TEXT          NOT NULL DEFAULT '',
  precio           NUMERIC(10,2) NOT NULL,
  duracion_minutos SMALLINT      NOT NULL CHECK (duracion_minutos >= 1),
  activo           BOOLEAN       NOT NULL DEFAULT TRUE,
  creado_en        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- Clientas: solo lo necesario para prestar el servicio.
-- El teléfono se guarda normalizado (ej. +56912345678) desde la aplicación.
CREATE TABLE servicios_cliente (
  id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                    VARCHAR(150) NOT NULL,
  telefono                  VARCHAR(20)  NOT NULL UNIQUE
                              CHECK (telefono ~ '^\+?[0-9]{8,15}$'),
  email                     VARCHAR(254) NULL,
  acepta_politica_privacidad BOOLEAN     NOT NULL DEFAULT FALSE,
  acepta_politica_en        TIMESTAMPTZ  NULL,
  creado_en                 TIMESTAMPTZ  NOT NULL DEFAULT now(),
  -- Si aceptó la política, debe quedar registrada la fecha:
  CONSTRAINT cliente_consentimiento_con_fecha
    CHECK (acepta_politica_privacidad = FALSE OR acepta_politica_en IS NOT NULL)
);

-- Email único solo cuando existe (varias clientas pueden no tener email).
CREATE UNIQUE INDEX cliente_email_unico_idx
  ON servicios_cliente (lower(email))
  WHERE email IS NOT NULL;

-- Personal contratado: aquí el RUT sí tiene sentido. Tabla NO pública (ver RLS).
CREATE TABLE servicios_profesional (
  id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  rut    VARCHAR(12)  NOT NULL UNIQUE,
  activo BOOLEAN      NOT NULL DEFAULT TRUE
);

-- N:M  Profesional <-> Servicio
CREATE TABLE servicios_profesional_servicios (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profesional_id BIGINT NOT NULL REFERENCES servicios_profesional(id) ON DELETE CASCADE,
  servicio_id    BIGINT NOT NULL REFERENCES servicios_servicio(id)    ON DELETE CASCADE,
  UNIQUE (profesional_id, servicio_id)
);

-- Horarios (turnos semanales): dia 0=Lunes ... 6=Domingo
CREATE TABLE servicios_horariotrabajo (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profesional_id BIGINT   NOT NULL REFERENCES servicios_profesional(id) ON DELETE CASCADE,
  dia            SMALLINT NOT NULL CHECK (dia BETWEEN 0 AND 6),
  hora_entrada   TIME     NOT NULL,
  hora_salida    TIME     NOT NULL,
  CONSTRAINT horario_salida_despues_entrada CHECK (hora_salida > hora_entrada)
);

CREATE TABLE servicios_bloqueohorario (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profesional_id BIGINT      NOT NULL REFERENCES servicios_profesional(id) ON DELETE CASCADE,
  inicio         TIMESTAMPTZ NOT NULL,
  fin            TIMESTAMPTZ NOT NULL,
  motivo         VARCHAR(200) NOT NULL DEFAULT '',
  CONSTRAINT bloqueo_fin_despues_inicio CHECK (fin > inicio)
);

CREATE TABLE servicios_cita (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id     BIGINT      NOT NULL REFERENCES servicios_cliente(id)     ON DELETE RESTRICT,
  profesional_id BIGINT      NOT NULL REFERENCES servicios_profesional(id) ON DELETE RESTRICT,
  servicio_id    BIGINT      NOT NULL REFERENCES servicios_servicio(id)    ON DELETE RESTRICT,
  inicio         TIMESTAMPTZ NOT NULL,
  fin            TIMESTAMPTZ NOT NULL,
  estado         VARCHAR(12) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','confirmada','cancelada')),
  creado_en      TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT cita_fin_despues_inicio CHECK (fin > inicio),
  -- Un profesional no puede tener dos citas activas que se pisen:
  CONSTRAINT cita_sin_solapamiento EXCLUDE USING gist (
    profesional_id WITH =, tstzrange(inicio, fin) WITH &&
  ) WHERE (estado IN ('pendiente','confirmada'))
);

CREATE INDEX cita_inicio_idx ON servicios_cita (inicio);
CREATE INDEX cita_profesional_inicio_idx ON servicios_cita (profesional_id, inicio);

-- =====================================================================
-- Seguridad: Row Level Security (Supabase)
-- Con RLS activado y SIN políticas, los roles `anon` y `authenticated`
-- (la anon key del navegador) no pueden leer ni escribir nada.
-- Tu backend (Django con conexión directa a Postgres, o la service_role
-- key) se salta RLS, así que sigue funcionando normal.
-- =====================================================================
ALTER TABLE servicios_servicio              ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_cliente               ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_profesional           ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_profesional_servicios ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_horariotrabajo        ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_bloqueohorario        ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios_cita                  ENABLE ROW LEVEL SECURITY;

-- Refuerzo: quitar privilegios directos a los roles públicos.
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;

-- Única excepción pública (opcional): el catálogo de servicios activos
-- puede leerse sin pasar por el backend. Bórralo si prefieres que todo
-- pase por Django.
GRANT SELECT ON servicios_servicio TO anon;
CREATE POLICY servicios_publicos_lectura
  ON servicios_servicio
  FOR SELECT
  TO anon
  USING (activo = TRUE);